import chess
import torch


def compute_legal_move_rate(
    model: torch.nn.Module,
    tokenizer,
    device: torch.device,
    num_samples: int = 10,
    max_moves: int = 50,
) -> float:
    """
    Computes the percentage of legal moves generated by the model starting from
    an empty board, playing against itself.
    """
    model.eval()
    
    total_generated = 0
    legal_generated = 0
    
    with torch.no_grad():
        for _ in range(num_samples):
            board = chess.Board()
            
            # Start sequence with BOS
            input_ids = [tokenizer.bos_id]
            
            for _ in range(max_moves):
                if board.is_game_over():
                    break
                
                # Context
                x = torch.tensor(input_ids, dtype=torch.long, device=device).unsqueeze(0)
                mask = torch.ones_like(x, dtype=torch.long, device=device)
                
                logits = model(x, mask)
                next_token_logits = logits[0, -1, :]
                
                # Greedily pick the highest probability token that is NOT a special token if possible
                # For a more robust test, we can just argmax
                next_token = int(next_token_logits.argmax().item())
                input_ids.append(next_token)
                
                token_str = tokenizer.decode([next_token]).strip()
                
                # Check if it's a legal move
                try:
                    move = board.parse_san(token_str) if "san" in tokenizer.__class__.__name__.lower() else chess.Move.from_uci(token_str)
                    if move in board.legal_moves:
                        board.push(move)
                        legal_generated += 1
                except Exception:
                    pass
                
                total_generated += 1

    if total_generated == 0:
        return 0.0
        
    return legal_generated / total_generated
